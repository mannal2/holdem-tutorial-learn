    await p.screenshot({path:'test-results/lesson-picker-320.png',fullPage:true});
    await picker.getByRole('button',{name:'닫기',exact:true}).click();
    await toCalls(p); await p.locator('#next').click(); await title(p,'나는 얼마');
    assert.equal((await read(p)).stepId,'call-amount');
    assert.equal(await p.locator('#chapter-label').textContent(),'첫걸음 체험');
