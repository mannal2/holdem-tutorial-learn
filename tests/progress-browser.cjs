    await p.locator('#previous').click();
    assert.deepEqual((await read(p)).completedLessonIds,['prototype']);
    await p.locator('#lesson-select').click();
    assert.match(await picker.locator('[data-lesson-id="prototype"]').textContent(),/완료/);
    await picker.getByRole('button',{name:'진도 초기화',exact:true}).click();
    await picker.getByRole('button',{name:'취소',exact:true}).click();
    assert.deepEqual((await read(p)).completedLessonIds,['prototype']);
    await picker.getByRole('button',{name:'진도 초기화',exact:true}).click();
    await picker.getByRole('button',{name:'초기화',exact:true}).click();
